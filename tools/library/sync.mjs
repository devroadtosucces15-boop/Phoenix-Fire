// Regenerates the machine-made library files from the code, so they cannot drift from it.
//   node tools/library/sync.mjs          write LIBRARY/BOT-COMMANDS.md and LIBRARY/ASSETS-INDEX.md
//   node tools/library/sync.mjs --check  exit 1 when either file is out of date (tests/library.test.mjs runs the same check)
// The hand-written library files (LIBRARY/README.md lists them) point at these; nothing here holds a secret.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { COMMANDS, APP_COMMANDS } from '../../bot/commanddefs.js';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const KIND = { 1: 'subcommand', 3: 'text', 4: 'number', 5: 'yes/no', 6: 'user', 7: 'channel', 8: 'role', 10: 'decimal', 11: 'file' };

const optLine = (o, depth = 0) => {
  const pad = '  '.repeat(depth + 1);
  const tags = [KIND[o.type] || `type ${o.type}`, o.required ? 'required' : 'optional'];
  if (o.autocomplete) tags.push('autocomplete');
  if (o.choices) tags.push(`choices: ${o.choices.map((c) => c.name).join(', ')}`);
  const own = `${pad}- \`${o.name}\` (${tags.join(', ')}): ${o.description || ''}`;
  return [own, ...(o.options || []).map((x) => optLine(x, depth + 1))].join('\n');
};

export function renderCommands() {
  const byName = new Map(COMMANDS.map((c) => [c.name, c]));
  const out = ['# Bot commands (generated)', '', 'Generated by `node tools/library/sync.mjs` from `bot/commanddefs.js`. Do not edit by hand; change the code and rerun.', ''];
  for (const [app, names] of Object.entries(APP_COMMANDS)) {
    out.push(`## ${app} (${names.length} command${names.length === 1 ? '' : 's'})`, '');
    if (!names.length) out.push('No commands (kept empty for the transition).', '');
    for (const n of names) {
      const c = byName.get(n);
      out.push(c ? `- **/${c.name}**: ${c.description}` : `- **/${n}**: (no definition found in COMMANDS)`);
      for (const o of c?.options || []) out.push(optLine(o));
    }
    out.push('');
  }
  const mapped = new Set(Object.values(APP_COMMANDS).flat());
  const loose = COMMANDS.filter((c) => !mapped.has(c.name)).map((c) => c.name);
  out.push('## Defined but not mapped to an app', '', loose.length ? loose.map((n) => `\`/${n}\``).join(', ') : 'None.', '');
  return out.join('\n');
}

const ASSET_DIRS = [
  ['phoenix/overlay', 'Crest, logo, favicons and theme layer laid over the built site'],
  ['bot/icons/phoenix', 'Emoji and icon set uploaded to every Discord app'],
  ['phoenix/card-looks', 'Card studio looks'],
  ['phoenix/share-art', 'Share-card art'],
  ['phoenix/source', 'Source art and fonts the builds read'],
  ['phoenix/legacy-assets', 'Older assets kept for the transition'],
];
export function renderAssets() {
  const out = ['# Asset index (generated)', '', 'Generated by `node tools/library/sync.mjs`. Lists what is on disk; the meaning of each group is in `LIBRARY/ASSETS.md`.', ''];
  for (const [dir, what] of ASSET_DIRS) {
    const abs = path.join(ROOT, dir);
    const files = fs.existsSync(abs) ? fs.readdirSync(abs).sort() : [];
    out.push(`## \`${dir}/\` (${files.length} items)`, '', what, '');
    for (const f of files.slice(0, 60)) {
      const st = fs.statSync(path.join(abs, f));
      out.push(`- \`${f}\`${st.isDirectory() ? ' (folder)' : ` (${st.size} bytes)`}`);
    }
    if (files.length > 60) out.push(`- ...and ${files.length - 60} more`);
    out.push('');
  }
  return out.join('\n');
}

const TARGETS = [['LIBRARY/BOT-COMMANDS.md', renderCommands], ['LIBRARY/ASSETS-INDEX.md', renderAssets]];
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, render] of TARGETS) {
    const want = render();
    const have = fs.existsSync(path.join(ROOT, file)) ? fs.readFileSync(path.join(ROOT, file), 'utf8') : '';
    if (have === want) continue;
    if (check) { stale++; console.log(`out of date: ${file}`); } else { fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true }); fs.writeFileSync(path.join(ROOT, file), want); console.log(`wrote ${file}`); }
  }
  if (check && stale) process.exit(1);
}
