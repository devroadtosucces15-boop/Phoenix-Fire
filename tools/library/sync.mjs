// Regenerates the machine-made library files from the code, so they cannot drift from it.
//   node tools/library/sync.mjs          write LIBRARY/BOT-COMMANDS.md, ASSETS-INDEX.md and SITEMAP-INDEX.md
//   node tools/library/sync.mjs --check  exit 1 when any of them is out of date (tests/library.test.mjs runs the same check)
// The hand-written library files (LIBRARY/README.md lists them) point at these; nothing here holds a secret.
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { COMMANDS, APP_COMMANDS } from '../../bot/commanddefs.js';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const KIND = { 1: 'subcommand', 3: 'text', 4: 'number', 5: 'yes/no', 6: 'user', 7: 'channel', 8: 'role', 10: 'decimal', 11: 'file' };

const optLine = (o, depth = 0) => {
  const pad = '  '.repeat(depth + 1);
  const tags = [KIND[o.type] || `type ${o.type}`, o.required ? 'required' : 'optional'];
  if (o.autocomplete) tags.push('autocomplete');
  if (o.choices) tags.push(`choices: ${o.choices.map((c) => c.name).join(', ')}`);
  const own = `${pad}- \`${o.name}\` (${tags.join(', ')}): ${o.description || ''}`;
  return [own, ...(o.options || []).map((x) => optLine(x, depth + 1))].join('\n');
};

export function renderCommands() {
  const byName = new Map(COMMANDS.map((c) => [c.name, c]));
  const out = ['# Bot commands (generated)', '', 'Generated by `node tools/library/sync.mjs` from `bot/commanddefs.js`. Do not edit by hand; change the code and rerun.', ''];
  for (const [app, names] of Object.entries(APP_COMMANDS)) {
    out.push(`## ${app} (${names.length} command${names.length === 1 ? '' : 's'})`, '');
    if (!names.length) out.push('No commands (kept empty for the transition).', '');
    for (const n of names) {
      const c = byName.get(n);
      out.push(c ? `- **/${c.name}**: ${c.description}` : `- **/${n}**: (no definition found in COMMANDS)`);
      for (const o of c?.options || []) out.push(optLine(o));
    }
    out.push('');
  }
  const mapped = new Set(Object.values(APP_COMMANDS).flat());
  const loose = COMMANDS.filter((c) => !mapped.has(c.name)).map((c) => c.name);
  out.push('## Defined but not mapped to an app', '', loose.length ? loose.map((n) => `\`/${n}\``).join(', ') : 'None.', '');
  return out.join('\n');
}

const ASSET_DIRS = [
  ['phoenix/overlay', 'Crest, logo, favicons and theme layer laid over the built site'],
  ['bot/icons/phoenix', 'Emoji and icon set uploaded to every Discord app'],
  ['phoenix/card-looks', 'Card studio looks'],
  ['phoenix/share-art', 'Share-card art'],
  ['phoenix/source', 'Source art and fonts the builds read'],
  ['phoenix/legacy-assets', 'Older assets kept for the transition'],
];
export function renderAssets() {
  const out = ['# Asset index (generated)', '', 'Generated by `node tools/library/sync.mjs`. Lists what is on disk; the meaning of each group is in `LIBRARY/ASSETS.md`.', ''];
  for (const [dir, what] of ASSET_DIRS) {
    const abs = path.join(ROOT, dir);
    const files = fs.existsSync(abs) ? fs.readdirSync(abs).sort() : [];
    out.push(`## \`${dir}/\` (${files.length} items)`, '', what, '');
    for (const f of files.slice(0, 60)) {
      const st = fs.statSync(path.join(abs, f));
      out.push(`- \`${f}\`${st.isDirectory() ? ' (folder)' : ` (${st.size} bytes)`}`);
    }
    if (files.length > 60) out.push(`- ...and ${files.length - 60} more`);
    out.push('');
  }
  return out.join('\n');
}

// Site map: build the site into a temp folder, list every html page, group by prefix. Data-driven pages (match, opponent, player) are listed
// as one pattern each with no counts, so a data refresh never makes the file stale.
const PATTERNS = [
  [/^match-/, 'match-<id>.html', 'One page per archived match', 'everyone', 'next/pages/matches.mjs'],
  [/^opp-/, 'opp-<id>.html', 'One page per opponent club', 'everyone', 'next/pages/matches.mjs'],
  [/^player-/, 'player-<name>.html', 'One page per squad player', 'everyone', 'next/pages/club.mjs'],
];
const audienceOf = (stem) => (stem === 'staff' || stem.startsWith('staff-') ? 'managers' : stem === 'hub' || stem.startsWith('hub-') ? 'signed-in members' : stem === 'members' || stem === 'member' ? 'members (claim and profile)' : 'everyone');
const titleOf = (html) => ((html.match(/<title>([^<]*)<\/title>/) || [])[1] || '').replace(/\s*[·|-]\s*phoenix fire\s*$/i, '').trim();
export function renderSitemap() {
  const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'pf-sitemap-')), 'site');
  const r = spawnSync(process.execPath, ['phoenix/build.mjs', '--out', out], { cwd: ROOT, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`phoenix/build.mjs failed: ${(r.stderr || r.stdout).slice(-300)}`);
  const srcDir = path.join(ROOT, 'next/pages');
  const registered = new Map();
  const templated = [];
  for (const f of fs.readdirSync(srcDir).filter((n) => n.endsWith('.mjs')).sort()) {
    const txt = fs.readFileSync(path.join(srcDir, f), 'utf8');
    for (const m of txt.matchAll(/\bP\(\s*'([\w-]+)\.html'/g)) if (!registered.has(m[1])) registered.set(m[1], `next/pages/${f}`);
    for (const m of txt.matchAll(/\bP\(\s*`([\w-]+?)-\$\{/g)) templated.push([m[1], `next/pages/${f}`]);
  }
  const rows = [];
  const patterns = new Map();
  for (const f of fs.readdirSync(out).filter((n) => n.endsWith('.html')).sort()) {
    const stem = f.slice(0, -5);
    const pat = PATTERNS.find(([re]) => re.test(stem));
    if (pat) { patterns.set(pat[1], pat); continue; }
    const t = templated.find(([pre]) => stem.startsWith(`${pre}-`));
    const src = stem === 'members' ? 'phoenix/claim.html' : registered.get(stem) || (t && t[1]) || (['404', 'offline'].includes(stem) ? 'next/lib/swap.mjs' : 'phoenix/build.mjs');
    rows.push(`| \`${f}\` | ${titleOf(fs.readFileSync(path.join(out, f), 'utf8')) || '(no title)'} | ${audienceOf(stem)} | \`${src}\` |`);
  }
  for (const [, name, what, aud, src] of patterns.values()) rows.push(`| \`${name}\` | ${what} | ${aud} | \`${src}\` |`);
  fs.rmSync(path.dirname(out), { recursive: true, force: true });
  return ['# Site map index (generated)', '', 'Generated by `node tools/library/sync.mjs` from a fresh `phoenix/build.mjs` build. Do not edit by hand. Meaning of each page group: `LIBRARY/SITEMAP.md`.', '',
    '| Page | Title | Audience | Source |', '|---|---|---|---|', ...rows, ''].join('\n');
}

// Feature flags: every key in config.json "features" with the level that may use it (off | owner | managers | members | public).
export function renderFlags() {
  const f = JSON.parse(fs.readFileSync(path.join(ROOT, 'config.json'), 'utf8')).features || {};
  const out = ['# Feature flags (generated)', '', 'Generated by `node tools/library/sync.mjs` from `config.json` `features`. Do not edit by hand. Levels are enforced by the Worker (`tests/flags.test.mjs`); the owner changes them in Boardroom, Switches.', ''];
  for (const lvl of ['public', 'members', 'managers', 'owner', 'off']) {
    const names = Object.keys(f).filter((k) => f[k] === lvl).sort();
    out.push(`## ${lvl} (${names.length})`, '', names.length ? names.map((n) => `\`${n}\``).join(', ') : 'None.', '');
  }
  const other = Object.keys(f).filter((k) => !['public', 'members', 'managers', 'owner', 'off'].includes(f[k]));
  if (other.length) out.push('## Other values', '', other.map((k) => `\`${k}\`: ${JSON.stringify(f[k])}`).join(', '), '');
  return out.join('\n');
}

const TARGETS = [['LIBRARY/BOT-COMMANDS.md', renderCommands], ['LIBRARY/ASSETS-INDEX.md', renderAssets], ['LIBRARY/SITEMAP-INDEX.md', renderSitemap], ['LIBRARY/FLAGS-INDEX.md', renderFlags]];
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, render] of TARGETS) {
    const want = render();
    const have = fs.existsSync(path.join(ROOT, file)) ? fs.readFileSync(path.join(ROOT, file), 'utf8') : '';
    if (have === want) continue;
    if (check) { stale++; console.log(`out of date: ${file}`); } else { fs.mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true }); fs.writeFileSync(path.join(ROOT, file), want); console.log(`wrote ${file}`); }
  }
  if (check && stale) process.exit(1);
}
