// Data for the project brain dashboard: reads the library files and returns plain objects and html strings. No server, no secrets.
// Credentials are names and places only: every cell goes through redact() so a value that slipped into a registry never reaches the page.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mapsModel } from './maps.mjs';
import { listNotes } from './inbox.mjs';
import { usageModel } from './usage.mjs';
import { readRoadmap, roadmapMetrics } from '../library/sync.mjs';

export const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const read = (f) => (fs.existsSync(path.join(ROOT, f)) ? fs.readFileSync(path.join(ROOT, f), 'utf8') : '');

export const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
// Anything that looks like a credential value, or a long hex id, is replaced. Names (UPPER_SNAKE) and plain words pass.
const SECRETISH = [/[A-Za-z0-9_-]{23,28}\.[A-Za-z0-9_-]{6,7}\.[A-Za-z0-9_-]{27,}/g, /gh[pousr]_[A-Za-z0-9]{20,}/g, /sk-[A-Za-z0-9_-]{20,}/g, /\b[0-9a-f]{32,}\b/g, /\b\d{17,20}\b/g];
export const redact = (s) => SECRETISH.reduce((a, re) => a.replace(re, '[hidden]'), String(s));

const inline = (s) => esc(s)
  .replace(/`([^`]+)`/g, '<code>$1</code>')
  .replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>')
  .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>');

// Small markdown renderer: headings, tables, lists, code fences, paragraphs. Enough for the library files.
export function md(src) {
  const out = [];
  const lines = src.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const l = lines[i];
    if (/^```/.test(l)) { const buf = []; while (++i < lines.length && !/^```/.test(lines[i])) buf.push(lines[i]); out.push(`<pre>${esc(buf.join('\n'))}</pre>`); continue; }
    if (/^\|.*\|\s*$/.test(l) && /^\|[\s:|-]+\|\s*$/.test(lines[i + 1] || '')) {
      const cells = (r) => r.trim().replace(/^\||\|$/g, '').split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, '|'));
      const head = cells(l); i += 2; const rows = [];
      for (; i < lines.length && /^\|.*\|\s*$/.test(lines[i]); i++) rows.push(cells(lines[i]));
      i--;
      out.push(`<div class="tw"><table><thead><tr>${head.map((h) => `<th>${inline(h)}</th>`).join('')}</tr></thead><tbody>${rows.map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`);
      continue;
    }
    const h = l.match(/^(#{1,4})\s+(.*)/);
    if (h) { out.push(`<h${h[1].length + 1}>${inline(h[2])}</h${h[1].length + 1}>`); continue; }
    if (/^\s*[-*]\s+/.test(l) || /^\s*\d+\.\s+/.test(l)) {
      const ordered = /^\s*\d+\./.test(l); const items = [];
      for (; i < lines.length && /^\s*([-*]|\d+\.)\s+/.test(lines[i]); i++) items.push(lines[i].replace(/^\s*([-*]|\d+\.)\s+/, ''));
      i--; out.push(`<${ordered ? 'ol' : 'ul'}>${items.map((x) => `<li>${inline(x)}</li>`).join('')}</${ordered ? 'ol' : 'ul'}>`);
      continue;
    }
    if (l.trim()) { const buf = [l]; while (i + 1 < lines.length && lines[i + 1].trim() && !/^(#|\||```|\s*[-*]\s|\s*\d+\.\s)/.test(lines[i + 1])) buf.push(lines[++i]); out.push(`<p>${inline(buf.join(' '))}</p>`); }
  }
  return out.join('\n');
}

// Libraries tab: one card per LIBRARY file (the roadmap has its own tab).
const LIB_INFO = {
  'ASSETS.md': 'Assets', 'ASSETS-INDEX.md': 'Assets index', 'DESIGN.md': 'Design', 'BOT.md': 'Bot', 'BOT-COMMANDS.md': 'Bot commands', 'FLAGS-INDEX.md': 'Feature flags',
  'SITEMAP.md': 'Site map', 'SITEMAP-INDEX.md': 'Site map index', 'RESOURCES.md': 'Resources', 'CLAIMS.md': 'File claims', 'LESSONS.md': 'Lessons', 'README.md': 'Library index',
};
export function libraries() {
  const dir = path.join(ROOT, 'LIBRARY');
  return fs.readdirSync(dir).filter((f) => LIB_INFO[f]).sort().map((f) => {
    const src = fs.readFileSync(path.join(dir, f), 'utf8');
    const verified = (src.match(/^Last verified: (\d{4}-\d{2}-\d{2})/m) || [])[1] || '';
    const generated = /Generated by `node tools\/library\/sync\.mjs`/.test(src);
    return { file: f, title: LIB_INFO[f], verified, generated, lines: src.split('\n').length, html: md(src.replace(/^# .*\n/, '')) };
  });
}

// References tab: PLANNING/RESOURCES.md links grouped by heading, plus the library's own group table.
export function references() {
  const groups = []; let cur = null;
  for (const l of read('PLANNING/RESOURCES.md').split('\n')) {
    const h = l.match(/^#{2,3}\s+(.*)/);
    if (h) { cur = { title: h[1], links: [] }; groups.push(cur); continue; }
    const m = l.match(/^\s*-\s+(https?:\/\/\S+)/);
    if (m && cur) cur.links.push(m[1]);
  }
  const table = [];
  for (const l of read('LIBRARY/RESOURCES.md').split('\n')) {
    const c = l.match(/^\| (?!Group|---)([^|]+) \| `([^`]+)` \| ([^|]+) \|/);
    if (c) table.push({ group: c[1].trim(), where: c[2], use: c[3].trim() });
  }
  return { groups: groups.filter((g) => g.links.length), table };
}

// Credentials tab: from bot/SECRETS-REGISTRY.md. Names, purpose, where it lives, set or not. Never a value.
export function credentials() {
  const src = read('bot/SECRETS-REGISTRY.md');
  const section = (title) => { const i = src.indexOf(`## ${title}`); if (i < 0) return []; const rest = src.slice(i + 3); const end = rest.search(/\n## /); return (end < 0 ? rest : rest.slice(0, end)).split('\n').filter((l) => /^\|/.test(l) && !/^\|[\s:|-]+\|$/.test(l)).slice(1); };
  const cells = (r) => r.trim().replace(/^\||\|$/g, '').split('|').map((c) => c.trim());
  const status = (w) => (/^(n\/a|no)$/i.test(w) ? 'none' : /not set/i.test(w) ? 'not set' : /not verified/i.test(w) ? 'unverified' : /\b(set|present)\b/i.test(w) ? 'set' : 'unverified');
  const secrets = section('Secrets: where each one lives').map(cells).filter((c) => c.length >= 5).map(([name, purpose, source, worker, github]) => ({
    names: [...name.matchAll(/`([A-Z0-9_]+)`/g)].map((m) => m[1]), purpose: redact(purpose), source: redact(source), worker: status(worker), github: status(github), workerNote: redact(worker), githubNote: redact(github),
  }));
  const apps = section('Discord apps').map(cells).filter((c) => c.length >= 5).map(([app, , key, endpoint, intents]) => ({ app: app.replace(/"/g, ''), publicKey: /wrangler/.test(key) ? 'in wrangler.toml' : redact(key), endpoint: endpoint.replace(/`/g, ''), intents }));
  const checked = (src.match(/^Last checked: ([\d-]+)/m) || [])[1] || '';
  return { checked, apps, secrets };
}

// Usage intelligence is generated by `node tools/brain/intel.mjs --write` (it reads local transcripts, which is too slow for every page load).
export function readIntel() {
  try { const j = JSON.parse(read('LIBRARY/state/intel.json')); return { generated: j.generated, items: j.items || [], lessons: j.lessons || [], sessions: (j.sessions || []).length }; } catch { return null; }
}

export function model() {
  const rm = readRoadmap();
  const metrics = roadmapMetrics(rm.items);
  const byId = new Map(rm.items.map((i) => [i.id, i]));
  const items = rm.items.map((i) => ({ ...i, blockedBy: i.dependsOn.filter((d) => byId.get(d)?.status !== 'DONE') }));
  return { generated: new Date().toISOString(), roadmap: { updated: rm.updated, items, inbox: rm.inbox, metrics, next: items.find((i) => i.status === 'NEXT')?.id || null }, libraries: libraries(), references: references(), credentials: credentials(), inbox: listNotes(), usage: usageModel(), intel: readIntel(), ...mapsModel() };
}

